# --------------------------------------------------------------------------- #
# Mo consumption — deterministic proof interests reach the real prompt,
# with NO real network/LLM call and no assertion on generated response text.
# --------------------------------------------------------------------------- #
class _FakeMessage:
    def __init__(self, content):
        self.content = content


class _FakeChoice:
    def __init__(self, content):
        self.message = _FakeMessage(content)


class _FakeResponse:
    def __init__(self, content):
        self.choices = [_FakeChoice(content)]


class _FakeCompletions:
    def __init__(self, content):
        self._content = content
        self.last_kwargs = None

    def create(self, **kwargs):
        self.last_kwargs = kwargs
        return _FakeResponse(self._content)


class _FakeChat:
    def __init__(self, content):
        self.completions = _FakeCompletions(content)


class _FakeAIClient:
    def __init__(self, content='{"mode": "read", "operations": '
                                '[{"intent": "GET_SCHEDULE_SUMMARY", "parameters": {}}]}'):
        self.chat = _FakeChat(content)


def test_saved_interests_reach_the_real_system_prompt_via_interpret(monkeypatch):
    fake = _FakeAIClient()
    monkeypatch.setattr(main, "ai_client", fake)

    main.AIService.interpret(
        "what's my schedule",
        user_interests={"game": ["Action"], "movie_tv": ["Anime"]},
    )

    sent_messages = fake.chat.completions.last_kwargs["messages"]
    system_content = next(m["content"] for m in sent_messages if m["role"] == "system")
    assert "USER-DECLARED INTERESTS" in system_content
    assert "Games: Action" in system_content
    assert "Movies & TV: Anime" in system_content


def test_no_interests_produces_no_interests_block_in_the_real_prompt(monkeypatch):
    fake = _FakeAIClient()
    monkeypatch.setattr(main, "ai_client", fake)

    main.AIService.interpret("what's my schedule", user_interests={})

    sent_messages = fake.chat.completions.last_kwargs["messages"]
    system_content = next(m["content"] for m in sent_messages if m["role"] == "system")
    assert "USER-DECLARED INTERESTS" not in system_content


def test_process_input_call_site_fetches_and_forwards_the_authenticated_users_interests(alice, monkeypatch):
    """End-to-end proof: PUT interests via the real API, then drive the real
    /api/process-input endpoint (with only the OpenAI boundary faked) and
    confirm the SAME saved values reached the real constructed prompt —
    i.e. retrieval AND forwarding both happen on the real request path, not
    just when calling AIService.interpret directly."""
    tc, user = alice
    tc.put("/api/profile/interests", json={"sport": ["Badminton"]})

    fake = _FakeAIClient()
    monkeypatch.setattr(main, "ai_client", fake)

    r = tc.post("/api/process-input", json={"user_input": "what's my schedule today"})
    assert r.status_code == 200, r.text

    sent_messages = fake.chat.completions.last_kwargs["messages"]
    system_content = next(m["content"] for m in sent_messages if m["role"] == "system")
    assert "Sports: Badminton" in system_content


