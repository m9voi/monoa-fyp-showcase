def test_put_saves_and_get_reflects_it(alice):
    tc, _ = alice
    r = tc.put("/api/profile/interests", json={"game": ["Action", "RPG"]})
    assert r.status_code == 200, r.text
    assert r.json()["interests"]["game"] == ["Action", "RPG"]
