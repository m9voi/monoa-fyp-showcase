def test_put_persists_across_a_fresh_db_read(alice):
    tc, user = alice
    tc.put("/api/profile/interests", json={"sport": ["Running", "Cycling"]})
    conn = db_layer.get_connection()
    try:
        rows = conn.execute(
            "SELECT value FROM user_interests WHERE user_id = ? AND category = 'sport' ORDER BY value",
            (user["id"],),
        ).fetchall()
        assert [r["value"] for r in rows] == ["Cycling", "Running"]
    finally:
        conn.close()


