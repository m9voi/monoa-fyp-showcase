def test_frontend_and_backend_interest_options_match_exactly():
    # The single most important cross-file consistency check: a value the
    # UI can select must be exactly a value the backend will accept.
    import re

    backend_src = _read("main.py")
    backend_block = backend_src[
        backend_src.index("INTEREST_OPTIONS: Dict[str, tuple] = {"):
        backend_src.index("INTEREST_VALUE_MAX_LENGTH")
    ]
    # Python dict literals need quoted keys ("game": (...)); the TS object
    # equivalent uses bare keys (game: [...]) — exclude the four category
    # names themselves so this only compares the actual interest VALUES.
    backend_values = set(re.findall(r'"([^"]+)"', backend_block)) - set(main.INTEREST_CATEGORIES)

    frontend_block = _INTERESTS_LIB[
        _INTERESTS_LIB.index("export const INTEREST_OPTIONS"):
        _INTERESTS_LIB.index("export type UserInterests")
    ]
    frontend_values = set(re.findall(r'"([^"]+)"', frontend_block))

    assert frontend_values == backend_values
