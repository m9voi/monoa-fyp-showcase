def test_one_users_interests_never_appear_for_another_user(alice, bob):
    ac, alice_user = alice
    bc, bob_user = bob
    ac.put("/api/profile/interests", json={"game": ["Action", "RPG"]})
    bc.put("/api/profile/interests", json={"game": ["Strategy"]})

    assert ac.get("/api/profile/interests").json()["interests"]["game"] == ["Action", "RPG"]
    assert bc.get("/api/profile/interests").json()["interests"]["game"] == ["Strategy"]

    # direct DB proof too — no cross-user row leakage
    from main import _get_user_interests
    assert _get_user_interests(alice_user["id"])["game"] == ["Action", "RPG"]
    assert _get_user_interests(bob_user["id"])["game"] == ["Strategy"]


